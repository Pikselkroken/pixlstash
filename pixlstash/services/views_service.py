def _prepare_root(root: str) -> None:
    """Create *root* and claim it, refusing a folder that already holds content.

    The marker is what authorises the rebuild's deletes. Without it a views root
    aimed at a folder of real pictures would be emptied on the next publish, so a
    non-empty unclaimed folder is refused rather than adopted.
    """
    if os.path.exists(root):
        if not os.path.isdir(root):
            raise ViewsError("That path is a file, not a folder.")
        marker = os.path.join(root, MARKER_NAME)
        if not os.path.exists(marker):
            try:
                occupied = bool(os.listdir(root))
            except OSError as exc:
                # Unreadable is not empty. Refusing is the only safe reading,
                # because the alternative is deleting inside a folder whose
                # contents could not be checked.
                raise ViewsError(f"Could not read that folder: {exc}") from exc
            if occupied:
                raise ViewsError(
                    "That folder already has things in it. Choose an empty "
                    "folder, or one PixlStash published views to before."
                )
    else:
        try:
            os.makedirs(root, exist_ok=True)
        except OSError as exc:
            raise ViewsError(f"Could not create that folder: {exc}") from exc
    try:
        with open(os.path.join(root, MARKER_NAME), "w", encoding="utf-8") as handle:
            handle.write(MARKER_TEXT)
    except OSError as exc:
        raise ViewsError(f"Could not write to that folder: {exc}") from exc


def _prune(directory: str) -> list[str]:
    """Remove every link under *directory*, and nothing that is the only copy.

    **This is the rule that stands between a rebuild and someone's pictures.**
    ``shutil.rmtree`` is not link-aware: it deletes a regular file as happily as
    a symlink, so a rebuild that used it would destroy anything the owner had
    dropped into a view folder - and every line of this feature's copy invites
    them to treat these folders as ordinary ones. So the deletes are decided per
    entry, and the test is exact rather than heuristic:

    * a **symlink** is removed - it is a path, and unlinking it loses nothing;
    * a regular file with ``st_nlink > 1`` is removed - another name for those
      bytes exists elsewhere, which is exactly what a hard link into the library
      is, so unlinking this one loses nothing;
    * **anything else stays**, and is named to the caller. A regular file whose
      only name is here is the owner's, however it arrived.

    A directory that still holds something afterwards is kept. Nothing here
    follows a symlinked directory: those are removed as links, not descended
    into, which is also what stops a symlink planted in the views root from
    steering the rebuild outside it.

    Returns:
        The paths that were kept, relative to *directory*, so the caller can say
        which folders it did not fully own.
    """
    kept: list[str] = []
    if not os.path.isdir(directory) or os.path.islink(directory):
        return kept
    for parent, dirs, files in os.walk(directory, topdown=False, followlinks=False):
        for name in files + dirs:
            path = os.path.join(parent, name)
            try:
                info = os.lstat(path)
                if stat.S_ISLNK(info.st_mode):
                    os.remove(path)
                    continue
                if stat.S_ISDIR(info.st_mode):
                    os.rmdir(path)  # bottom-up, so this succeeds iff it emptied
                    continue
                if stat.S_ISREG(info.st_mode) and info.st_nlink > 1:
                    os.remove(path)
                    continue
            except OSError as exc:
                logger.info("Views: keeping %s, which did not come away: %s", path, exc)
                if not os.path.lexists(path):
                    # It went away between the walk and the unlink - a viewer
                    # tidying up, another process, the owner. Nothing is kept,
                    # and re-``lstat``ing to find that out would raise inside
                    # this handler and abort the whole publish.
                    continue
                if name in dirs:
                    # A directory only survives because something inside it did.
                    # That thing is already named; naming its parent as well
                    # would report one kept file as two.
                    continue
            kept.append(os.path.relpath(path, directory))
    return kept


def _prune_all(root: str) -> list[str]:
    """Prune every kind folder under *root*, and report what would not come away."""
    kept: list[str] = []
    for folder in KIND_FOLDERS.values():
        kind_dir = os.path.join(root, folder)
        if os.path.islink(kind_dir):
            # A symlink standing where a kind folder goes would send the whole
            # rebuild through it and out of the views root. Remove the link
            # itself; whatever it pointed at is not ours to touch.
            try:
                os.remove(kind_dir)
            except OSError as exc:
                logger.warning("Views: could not remove the link %s: %s", kind_dir, exc)
                kept.append(folder)
            continue
        this_kind = _prune(kind_dir)
        kept.extend(f"{folder}/{entry}" for entry in this_kind)
        if os.path.isdir(kind_dir) and not this_kind:
            try:
                os.rmdir(kind_dir)
            except OSError as exc:
                logger.debug("Views: %s is not empty after pruning: %s", kind_dir, exc)
    return kept


def _link_target(mode: str, source: str, view_dir: str) -> str:
    """Return the value to link *source* as from inside *view_dir*.

    A symlink is stored relative when both sides share a device, so moving the
    library and its views together keeps every link valid; across devices a
    relative path is either impossible (different drive letters on Windows) or
    absurd, so the absolute path is stored. A hard link takes the real path
    either way - it is an inode reference, not a path.
    """
    if mode != SYMLINK:
        return source
    try:
        if os.stat(os.path.dirname(source)).st_dev == os.stat(view_dir).st_dev:
            return os.path.relpath(source, view_dir)
    except (OSError, ValueError) as exc:
        # ValueError is the Windows case: os.path.relpath refuses two drive
        # letters outright. st_dev already separates those, so this is the belt
        # for a filesystem whose device ids agree across a boundary relpath
        # still will not cross.
        logger.debug("Views: falling back to an absolute link for %s: %s", source, exc)
    return source


def publish(
    vault,
    root: str,
    kinds: Iterable[str],
    collected: dict[str, list[tuple]],
    other_library_roots: Iterable[str] = (),
) -> PublishReport:
    """Rebuild the views tree at *root* from the library, and report what landed.

    The rebuild is a full re-derive: each published kind's folder is removed and
    written again. That costs a fraction of a second even for a large library
    (50,000 symlinks measured at 0.46 s to create and 0.34 s to remove), so there
    is no incremental path to get wrong, and a tree of links is disposable by
    construction.
    """
    with _PUBLISH_LOCK:
        return _publish_locked(vault, root, kinds, collected, other_library_roots)


def _publish_locked(
    vault, root, kinds, collected, other_library_roots=()
) -> PublishReport:
    kinds = [kind for kind in KIND_FOLDERS if kind in set(kinds)]
    check_views_root(root, vault, other_library_roots)
    _prepare_root(root)
    report = PublishReport()

    sample = next(
        (
            resolved
            for entries in collected.values()
            for _, _, pictures in entries
            for resolved in (
                ImageUtils.resolve_picture_path(vault.image_root, p.file_path)
                for p in pictures
            )
            if resolved and os.path.isfile(resolved)
        ),
        None,
    )
    if sample is not None:
        # Probed BEFORE anything is removed, so a folder that turns out not to
        # hold links does not cost the owner the tree they already had.
        mode, reason = probe_link_support(root, sample)
        if mode is None:
            raise ViewsError(reason)
        report.link_mode = mode

    # EVERY kind folder is pruned, not only the requested ones. Publishing
    # ``people`` alone after publishing ``people,sets`` must not leave ``Sets/``
    # behind full of links nothing will ever refresh: a kind that is switched off
    # is a kind whose folder should not exist. This is also what makes an empty
    # ``kinds`` mean an empty tree, which is what the API says it means.
    report.kept_by_owner = _prune_all(root)

    if sample is None:
        # Nothing to link, and the tree has just been emptied, which is the
        # honest answer when the last member of every view was removed.
        return report

    for kind in kinds:
        kind_dir = resolve_path_within(root, KIND_FOLDERS[kind])
        try:
            os.makedirs(kind_dir, exist_ok=True)
        except OSError as exc:
            logger.info("Views: could not create %s: %s", kind_dir, exc)
            report.skipped_unlinkable.append(KIND_FOLDERS[kind])
            continue
        taken_folders: set[str] = set()
        for entity_id, name, pictures in collected[kind]:
            folder = _unique(
                taken_folders,
                safe_component(name, f"{KIND_FOLDERS[kind]} {entity_id}"),
                str(entity_id),
            )
            view_dir = resolve_path_within(kind_dir, folder)
            try:
                os.makedirs(view_dir, exist_ok=True)
            except OSError as exc:
                # One folder PixlStash cannot create - a Windows reserved name
                # like ``CON``, a path over the length limit, a permission - is
                # that folder's problem. Naming it beats a 500 that loses the
                # whole tree, and beats a tree that quietly lacks it.
                logger.info("Views: could not create %s: %s", view_dir, exc)
                report.skipped_unlinkable.append(f"{KIND_FOLDERS[kind]}/{folder}")
                continue
            report.folders += 1
            taken_files: set[str] = set()
            for picture in pictures:
                source = ImageUtils.resolve_picture_path(
                    vault.image_root, picture.file_path
                )
                if not source or not os.path.isfile(source):
                    report.skipped_missing += 1
                    continue
                link_name = _unique(
                    taken_files,
                    safe_component(os.path.basename(source), f"{picture.id}"),
                    str(picture.id),
                )
                link_path = resolve_path_within(view_dir, link_name)
                target = _link_target(mode, source, view_dir)
                try:
                    if mode == SYMLINK:
                        os.symlink(target, link_path)
                    else:
                        os.link(target, link_path)
                except OSError as exc:
                    # A hard link that cannot reach this file's drive is the
                    # expected case for a library spanning two disks. Name it
                    # rather than failing the whole publish.
                    logger.info(
                        "Views: could not link %s into %s (%s mode): %s",
                        source,
                        view_dir,
                        mode,
                        exc,
                    )
                    entry = f"{KIND_FOLDERS[kind]}/{folder}"
                    if entry not in report.skipped_unlinkable:
                        report.skipped_unlinkable.append(entry)
                    continue
                report.links += 1

    logger.info(
        "Views: published %d links in %d folders at %s using %s links "
        "(%d files missing, %d folders partly unlinkable)",
        report.links,
        report.folders,
        root,
        report.link_mode,
        report.skipped_missing,
        len(report.skipped_unlinkable),
    )
    return report


def remove(root: str) -> None:
    """Remove a published views tree, leaving a folder PixlStash did not create.

    Only the kind folders and the marker go. The root itself stays because the
    owner chose it and may have made it for this; deleting it would be tidier and
    would be the one destructive surprise this feature could still produce.
    """
    with _PUBLISH_LOCK:
        _remove_locked(root)


def _remove_locked(root: str) -> None:
    if not root or not os.path.isdir(root):
        return
    if not os.path.exists(os.path.join(root, MARKER_NAME)):
        logger.warning(
            "Views: refusing to clear %s because it carries no %s marker.",
            root,
            MARKER_NAME,
        )
        return
    kept = _prune_all(root)
    if kept:
        # The marker stays while anything is still standing in the tree. It is
        # what tells the reference-folder scan to leave these files alone, and
        # dropping it over a partial removal would hand every surviving link to
        # the next scan as a new picture.
        logger.warning(
            "Views: %s still holds %d entries PixlStash did not put there, so "
            "the tree and its marker are left in place: %s",
            root,
            len(kept),
            ", ".join(kept[:10]),
        )
        return
    try:
        os.remove(os.path.join(root, MARKER_NAME))
    except OSError as exc:
        logger.warning("Views: could not remove the marker in %s: %s", root, exc)
