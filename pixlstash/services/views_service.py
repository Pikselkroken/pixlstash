logger = get_logger(__name__)

SYMLINK = "symlink"
HARDLINK = "hardlink"

#: The folder name each kind publishes under, and the order they are built in.
KIND_FOLDERS = {"people": "People", "sets": "Sets", "projects": "Projects"}

#: Written at the root the first time PixlStash publishes there. Its presence is
#: the only thing that authorises deleting a subtree, so a view root aimed at a
#: folder of real pictures is refused instead of emptied.
MARKER_NAME = ".pixlstash-views"
MARKER_TEXT = (
    "This folder is generated by PixlStash. Every file in it is a link to a "
    "picture that lives elsewhere; deleting the folder deletes no picture.\n"
)

#: Directory names that mark a cloud-sync root. A sync client follows a link and
#: uploads the file's content again rather than syncing the link, so publishing
#: into one would copy the whole library into the owner's cloud quota - the exact
#: duplication views exist to avoid.
#: Deliberately NOT ``.dropbox``: the Dropbox client keeps that one in the home
#: directory, not in the synced folder, so treating it as a marker refused every
#: path under ``$HOME`` for anyone running Dropbox at all. The entries below live
#: in the synced tree itself.
_SYNC_MARKERS = {
    ".dropbox.cache",
    ".dropbox.attr",
    ".onedrive",
    ".tmp.drivedownload",
    ".tmp.driveupload",
    "com~apple~clouddocs",
}
_SYNC_DIR_NAMES = {
    "dropbox",
    "onedrive",
    "onedrive - personal",
    "google drive",
    "googledrive",
    "my drive",
    "icloud drive",
    "nextcloud",
    "pcloud drive",
    "creative cloud files",
}

#: One publish at a time. The route's handler is sync, so FastAPI runs it in a
#: threadpool and two saves can overlap - and a rebuild removes a subtree before
#: it writes it, so overlapping ones would delete each other's work and leave a
#: tree neither request asked for. Nothing outside the views root is at risk
#: either way; this is about the result being the one that was requested.
_PUBLISH_LOCK = threading.Lock()

_UNSAFE_NAME = re.compile(r'[<>:"/\\|?*\x00-\x1f]')
_TRAILING = " ."

#: Longest entity or file name component the tree writes. See safe_component.
_MAX_COMPONENT = 80


class ViewsError(Exception):
    """A views root that must not be published to, with the reason for a human."""


@dataclass
class PublishReport:
    """What one publish actually did, so the UI can say it rather than imply it."""

    link_mode: str = SYMLINK
    folders: int = 0
    links: int = 0
    skipped_missing: int = 0
    #: View folders where at least one link could not be made - NOT folders that
    #: are absent. A folder here exists and is incomplete, which is the thing the
    #: owner has to be told, because a partial tree reads as a whole one.
    skipped_unlinkable: list[str] = field(default_factory=list)
    #: Entries the rebuild refused to delete because they were not links: the
    #: owner's own files, sitting in a view folder. They are reported rather than
    #: removed, and they are the reason the rebuild does not use ``rmtree``.
    kept_by_owner: list[str] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {
            "link_mode": self.link_mode,
            "folders": self.folders,
            "links": self.links,
            "skipped_missing": self.skipped_missing,
            "skipped_unlinkable": self.skipped_unlinkable,
            "kept_by_owner": self.kept_by_owner,
        }


def safe_component(name: str, fallback: str) -> str:
    """Return *name* as one filesystem path component.

    Entity names are free text and routinely contain ``/``, ``:`` or a trailing
    dot, all of which are either a path separator or illegal on Windows. The
    replacement is deliberately lossy and deliberately not unique: uniqueness is
    the caller's job via :func:`_unique`, because two characters really can be
    called the same thing.

    It is also truncated, which is not cosmetic. A component over ``NAME_MAX``
    is ``ENAMETOOLONG`` on Linux, and a views path is already four segments deep
    before the name - an unremarkable set name plus a long filename clears
    Windows' 260-character ``MAX_PATH`` between them. Truncating loses a suffix;
    not truncating loses the folder.
    """
    cleaned = _UNSAFE_NAME.sub("_", (name or "").strip()).rstrip(_TRAILING).strip()
    if len(cleaned) > _MAX_COMPONENT:
        cleaned = cleaned[:_MAX_COMPONENT].rstrip(_TRAILING).strip()
    return cleaned or fallback


def _unique(taken: set[str], candidate: str, suffix: str) -> str:
    """Return *candidate*, disambiguated with *suffix* until the name is free.

    It loops rather than suffixing once, because the disambiguated form can
    itself be taken: an entity genuinely called ``0412 (7).png`` collides with
    the name picture 7 would be given, and a single pass would hand back a
    duplicate - an ``EEXIST`` at link time, reported to the owner as if the
    filesystem had refused the link.
    """
    if candidate not in taken:
        taken.add(candidate)
        return candidate
    stem, ext = os.path.splitext(candidate)
    disambiguated = f"{stem} ({suffix}){ext}"
    attempt = 2
    while disambiguated in taken:
        disambiguated = f"{stem} ({suffix}-{attempt}){ext}"
        attempt += 1
    taken.add(disambiguated)
    return disambiguated


