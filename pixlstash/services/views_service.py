def _sync_root_marker(directory: str) -> Optional[str]:
    """Return the cloud-sync marker found at or above *directory*, if any.

    The walk stops **below** the home directory, and that bound is the whole
    reason this check is usable. Sync clients keep configuration in ``$HOME``
    (``~/.dropbox``) and their synced tree beside it (``~/Dropbox``), so a walk
    that reached ``$HOME`` - let alone ``/`` - reported every path a Dropbox user
    could possibly pick as synced, with no override and a message asserting
    something untrue of the folder they chose. Anything at or above ``$HOME`` is
    not a sync root; something under it may be.
    """
    current = os.path.abspath(directory)
    try:
        stop = os.path.normcase(os.path.abspath(os.path.expanduser("~")))
    except (OSError, RuntimeError) as exc:
        logger.debug("Views: no home directory to bound the sync scan: %s", exc)
        stop = None
    while True:
        if stop is not None and os.path.normcase(current) == stop:
            return None
        if os.path.basename(current).lower() in _SYNC_DIR_NAMES:
            return os.path.basename(current)
        try:
            entries = {entry.lower() for entry in os.listdir(current)}
        except OSError as exc:
            logger.debug(
                "Views: could not list %s while looking for a sync marker: %s",
                current,
                exc,
            )
            entries = set()
        found = _SYNC_MARKERS & entries
        if found:
            return sorted(found)[0]
        parent = os.path.dirname(current)
        if parent == current:
            return None
        current = parent


def same_root(a: Optional[str], b: Optional[str]) -> bool:
    """Whether two host paths name the same views folder.

    A raw string comparison is not enough and the failure is silent: a file
    picker returns ``/home/me/Views`` one time and ``/home/me/Views/`` the next,
    Windows and macOS spell the same directory in several cases, and ``.``
    components survive a round trip through JSON. Any of those made the caller
    believe the folder had *changed* - so it published the new tree and then
    removed it again as "the old one", reporting success over an empty folder.
    """
    if not a or not b:
        return a == b
    return _resolved(a) == _resolved(b)


def _resolved(path: str) -> str:
    """One host path, normalised the one way this module compares them."""
    absolute = os.path.abspath(path)
    try:
        absolute = os.path.realpath(absolute)
    except OSError as exc:
        logger.debug("Views: could not resolve %s: %s", path, exc)
    return os.path.normcase(absolute)


def roots_overlap(a: Optional[str], b: Optional[str]) -> bool:
    """Whether one views root sits **strictly inside** the other.

    Publishing into a folder under the previous root - or over it - means the
    "remove the old tree" step that runs next walks the tree just written and
    deletes it, then reports success over an empty folder. It is the same
    silent shape :func:`same_root` was written for, reached by containment
    instead of by spelling, so it is refused before anything is written.

    Equal roots are deliberately not an overlap: nothing is removed in that
    case, which is exactly what :func:`same_root` is asked first.
    """
    if not a or not b:
        return False
    first, second = _resolved(a), _resolved(b)
    if first == second:
        return False
    return first.startswith(second + os.sep) or second.startswith(first + os.sep)


def check_views_root(root: str, vault, other_library_roots: Iterable[str] = ()) -> None:
    """Raise :class:`ViewsError` when *root* must not hold the views tree.

    Each refusal is a measured failure rather than a caution:

    * **Inside the library root.** ``library_backup_service`` refuses to archive
      a symlinked payload (``Refusing symlinked library payload``), so a views
      tree under ``image_root`` breaks the owner's backups outright.
    * **Inside a reference folder.** The reference-folder scan lists symlinked
      files in ``os.walk``'s ``files``, so every picture would be indexed a
      second time under its view path.
    * **Containing the library.** The same two problems, reached from the other
      side, plus a rebuild that would delete into the library.
    * **A restricted system directory**, by the shared blocklist, resolved first
      so a symlink cannot launder one past it.
    * **A cloud-sync folder.** The client follows links and uploads the content,
      which duplicates the library rather than referencing it. This one is a
      **precaution, not a measurement**: no sync client was available to test
      against, and the refusal exists so the answer never has to be known. It is
      detected by name and by the client's own marker directories, so it is the
      one refusal here that can be wrong in both directions.
    """
    if not root or not os.path.isabs(root):
        raise ViewsError("Choose a full path for the views folder.")

    # The same blocklist every other path-taking route applies, on the resolved
    # path. Without it this function's refusals were all *relative* - inside the
    # library, inside a reference folder, a sync folder - and a root that was
    # none of those was accepted anywhere on the disk, including a system
    # directory the rest of the app refuses outright. `_prepare_root` then
    # creates the folder and writes the marker into it.
    # `os.path.realpath`, not this module's `_resolved`: that one applies
    # `normcase`, which lowercases on Windows, and the blocklist entries are
    # spelled `C:\Windows`. Passing a case-folded path made the check match
    # nothing on Windows - a refusal that never fires is worse than none,
    # because the coverage matrix records it as present.
    blocked = validate_reference_folder_path(os.path.realpath(os.path.abspath(root)))
    if blocked:
        raise ViewsError(blocked)

    image_root = getattr(vault, "image_root", None)
    if image_root:
        if path_is_within(root, image_root):
            raise ViewsError(
                "That folder is inside the library. Backups refuse a library "
                "containing links, so choose a folder outside it."
            )
        if path_is_within(image_root, root):
            raise ViewsError(
                "That folder contains the library itself. Choose one beside it "
                "rather than above it."
            )

    for reference_root in getattr(vault, "reference_folder_roots", lambda: ())():
        if path_is_within(root, reference_root):
            raise ViewsError(
                "That folder is inside a reference folder, so the next scan "
                "would index every link as a second copy of the picture."
            )
        if path_is_within(reference_root, root):
            raise ViewsError(
                "That folder contains a reference folder. Choose one beside "
                "your pictures rather than above them."
            )

    for library_root in other_library_roots:
        if path_is_within(root, library_root) or path_is_within(library_root, root):
            raise ViewsError(
                "That folder overlaps another library you have registered. "
                "Backups refuse a library containing links, so choose a folder "
                "outside every library."
            )

    marker = _sync_root_marker(root)
    if marker:
        raise ViewsError(
            f"That folder is synced by a cloud client ({marker}). Sync clients "
            "upload the file a link points at instead of the link, which would "
            "copy your whole library into the cloud. Choose a local folder."
        )


def probe_link_support(directory: str, target_file: str) -> tuple[Optional[str], str]:
    """Ask *directory*'s filesystem whether it can link to *target_file*.

    Attempts one symlink and then one hard link, removing whatever it made. The
    answer is measured rather than predicted because it depends on the
    filesystem (exFAT and VFAT refuse both), on whether the two paths share a
    device (a hard link cannot cross one) and, on Windows, on whether this
    process holds ``SeCreateSymbolicLinkPrivilege`` - which administrator rights
    or Developer Mode grant and nothing in the file's metadata reveals.

    Returns:
        ``(mode, reason)`` where *mode* is :data:`SYMLINK`, :data:`HARDLINK` or
        ``None``, and *reason* explains a ``None`` to the owner.
    """
    probe = os.path.join(directory, ".pixlstash-views-probe")
    for mode, make in ((SYMLINK, os.symlink), (HARDLINK, os.link)):
        try:
            make(target_file, probe)
        except OSError as exc:
            logger.info(
                "Views: %s links are unavailable in %s (target %s): %s",
                mode,
                directory,
                target_file,
                exc,
            )
            continue
        finally:
            if os.path.lexists(probe):
                try:
                    os.remove(probe)
                except OSError as exc:
                    logger.warning(
                        "Views: could not remove the link probe %s: %s", probe, exc
                    )
        return mode, ""
    return None, (
        "This folder cannot hold links. exFAT and FAT drives have neither kind, "
        "and on Windows symbolic links need administrator rights or Developer "
        "Mode. Choose a folder on an internal drive."
    )


